/**
 * Reconciles requested in-points against what the downloaded files actually
 * contain, and reports every scene whose footage falls short.
 *
 * Two distinct failures are handled here:
 *
 *  1. In-point at or past the end of the source. The decoder yields ZERO frames,
 *     tpad has no last frame to clone, and concat receives an empty stream —
 *     the render fails, or worse, silently loses a scene. In-points are derived
 *     from provider-reported durations (buildNasaSourceWindows) or from
 *     render_clip_slices rows that may predate a source being replaced, so a
 *     stale or wrong duration lands here. The in-point is pulled back to the
 *     latest position that still yields the requested footage.
 *
 *  2. Source shorter than the slot. This renders as a freeze frame via tpad.
 *     That is a deliberate fallback, not a bug — but it must never be silent,
 *     so it is logged with the scene, the source, and both durations.
 *
 * The REQUESTED DURATION IS NEVER CHANGED. It is the timeline contract: shorten
 * a clip here and every downstream slot shifts.
 */
async function reconcileClipSources(jobId, clips, clipPaths, downloadFailures = []) {
  const durations = new Array(clips.length).fill(null);
  // downloader's asyncPool takes (limit, items, worker) — not the clip-slices order.
  await asyncPool(
    4,
    clips.map((_, index) => index),
    async (index) => {
      const localPath = clipPaths.get(index);
      if (localPath) durations[index] = await probeSourceDuration(localPath);
    },
  );

  // ── Last-resort clip substitution ─────────────────────────────────────────
  // A clip with no usable file — every source dead, or the download landed but
  // does not decode — is rebound to a NEIGHBOURING clip's file, continuing from
  // where the neighbour's slot ends. The clamp/freeze pass below then bounds it
  // exactly like any short source, so the gap renders as extended footage (or a
  // held final frame when the neighbour has nothing left), never as a failed
  // chunk. A project with one extended shot beats a project that fails at 95%
  // twice, which is what the 2026-08-09 retry run measured.
  const failureByIndex = new Map(downloadFailures.map((failure) => [failure.index, failure]));
  const substitutions = [];
  for (let index = 0; index < clips.length; index++) {
    if (durations[index] != null) continue;
    const reason =
      failureByIndex.get(index)?.reason ??
      (clipPaths.get(index) ? 'downloaded file does not decode' : 'no source downloaded');

    // Nearest usable clip, preferring the previous one: extending backwards
    // continues footage the viewer has already seen into the gap, which reads
    // as a lingering shot rather than a jump.
    let donor = -1;
    for (let offset = 1; offset < clips.length; offset++) {
      if (index - offset >= 0 && durations[index - offset] != null) {
        donor = index - offset;
        break;
      }
      if (index + offset < clips.length && durations[index + offset] != null) {
        donor = index + offset;
        break;
      }
    }
    if (donor < 0) {
      // Nothing in this chunk decodes at all. Degrading every clip to nothing
      // is not a render; this is the one case that must still fail, and it
      // fails saying exactly why.
      throw new Error(
        `NO_USABLE_SOURCES: none of the ${clips.length} clips in this chunk could be downloaded or decoded ` +
          `(first failure: ${reason})`,
      );
    }

    const requestedDuration = clips[index].end - clips[index].start;
    // Continue from the donor slot's own end point, so the substitute does not
    // replay footage the donor's slot already shows.
    const start = clips[donor].end;
    clipPaths.set(index, clipPaths.get(donor));
    durations[index] = durations[donor];
    clips = clips.map((clip, i) =>
      i === index ? { ...clip, start, end: start + requestedDuration } : clip,
    );
    substitutions.push({ index, donor, sceneId: clips[index].scene_id ?? null, reason });
    logger.error(
      {
        jobId,
        clipIndex: index,
        sceneId: clips[index].scene_id ?? null,
        providerClipId: clips[index].provider_clip_id ?? null,
        donorIndex: donor,
        donorSceneId: clips[donor].scene_id ?? null,
        requestedDurationSec: Number(requestedDuration.toFixed(3)),
        reason,
      },
      'CLIP DEGRADED: unrenderable clip replaced by extending a neighbouring clip',
    );
  }

  let clampedInPoints = 0;
  let freezeFrames = 0;

  const reconciled = clips.map((clip, index) => {
    const requestedDuration = clip.end - clip.start;
    const sourceDuration = durations[index];
    if (sourceDuration == null) return clip;

    let start = clip.start;
    if (start >= sourceDuration - MIN_USABLE_SOURCE_SECONDS) {
      start = Math.max(0, sourceDuration - requestedDuration);
      clampedInPoints += 1;
      logger.warn(
        {
          jobId,
          clipIndex: index,
          sceneId: clip.scene_id ?? null,
          providerClipId: clip.provider_clip_id ?? null,
          requestedInPointSec: Number(clip.start.toFixed(3)),
          clampedInPointSec: Number(start.toFixed(3)),
          sourceDurationSec: Number(sourceDuration.toFixed(3)),
        },
        'In-point past end of source; clamped to keep the clip decodable',
      );
    }

    const availableDuration = Math.max(0, sourceDuration - start);
    if (availableDuration + 1e-3 < requestedDuration) {
      freezeFrames += 1;
      logger.warn(
        {
          jobId,
          clipIndex: index,
          sceneId: clip.scene_id ?? null,
          providerClipId: clip.provider_clip_id ?? null,
          requestedDurationSec: Number(requestedDuration.toFixed(3)),
          sourceDurationSec: Number(sourceDuration.toFixed(3)),
          availableAfterInPointSec: Number(availableDuration.toFixed(3)),
          freezeFrameSec: Number((requestedDuration - availableDuration).toFixed(3)),
        },
        'Source shorter than its slot; the shortfall renders as a freeze frame',
      );
    }

    return { ...clip, start, end: start + requestedDuration };
  });

  if (clampedInPoints > 0 || freezeFrames > 0 || substitutions.length > 0) {
    logger.warn(
      { jobId, clips: clips.length, clampedInPoints, freezeFrames, substitutions: substitutions.length },
      'Clip source reconciliation adjusted this job',
    );
  }
  return reconciled;
}

/**
 * Validates the job payload at enqueue time.
 * Returns a string error message or null if valid.
 */
function validatePayload(payload) {
  const { clips, audio_url, width, height, fps, transition, transition_duration, format } = payload;

  if (!Array.isArray(clips) || clips.length === 0) return 'clips must be a non-empty array';
  if (clips.length > config.maxClips) return `clip count ${clips.length} exceeds MAX_CLIPS=${config.maxClips}`;

  for (let i = 0; i < clips.length; i++) {
    const c = clips[i];
    if (!c.clip_url) return `clips[${i}].clip_url is required`;
    if (typeof c.start !== 'number' || typeof c.end !== 'number') return `clips[${i}].start/end must be numbers`;
    if (c.end <= c.start) return `clips[${i}].end must be greater than start`;
  }

  const totalDuration = clips.reduce((sum, c) => sum + (c.end - c.start), 0);
  if (totalDuration > config.maxDurationSeconds) {
    return `total duration ${totalDuration.toFixed(1)}s exceeds MAX_DURATION_SECONDS=${config.maxDurationSeconds}`;
  }

  if (!payload.is_chunk && !audio_url) return 'audio_url is required';
  if (!width || !height || !fps) return 'width, height, and fps are required';
  if (!SUPPORTED_TRANSITIONS.has(transition)) {
    return `transition must be one of: ${[...SUPPORTED_TRANSITIONS].join(', ')}`;
  }
  if (typeof transition_duration !== 'number' || transition_duration <= 0) {
    return 'transition_duration must be a positive number';
  }
  if (!['mp4', 'webm'].includes(format)) return 'format must be "mp4" or "webm"';

  return null; // valid
}

/**
 * Runs FFmpeg using -filter_complex_script and returns a promise that
 * resolves with the final output path or rejects with full stderr.
 *
 * @param {object} params
 * @param {Array<{path: string, start: number, duration: number}>} params.clipInputs - Clip sources (local or remote URL) with trim params
 * @param {string}   params.audioPath      - Local audio file path
 * @param {string}   params.scriptPath     - filter_complex_script file path
 * @param {string}   params.finalVideoLabel- e.g. '[vout]'
 * @param {string}   params.outputPath     - Absolute path for the output file
 * @param {number}   params.fps
 * @param {AbortSignal} params.signal      - Abort signal (hard timeout)
 */
async function runFfmpeg({ jobId, clipInputs, audioPath, scriptPath, finalVideoLabel, outputPath, fps, signal }) {
  const releaseFfmpeg = await acquireFfmpegSlot(jobId, signal);
  try {
    return await new Promise((resolve, reject) => {
    let stderrLines = [];
    let killed = false;

    // Niced below node so a saturated encode never starves the API's event
    // loop off the cpu — see config.ffmpegNiceness.
    const cmd = ffmpeg({ niceness: config.ffmpegNiceness });

    // Add all video clip inputs with input-level trimming (-ss and -t)
    clipInputs.forEach((ci) => {
      cmd.input(ci.path).inputOptions([
        '-ss', String(ci.start),
        '-t', String(ci.duration)
      ]);
    });

    // Add audio input only if provided
    let audioInputIndex = -1;
    if (audioPath) {
      cmd.input(audioPath);
      audioInputIndex = clipInputs.length;
    }

    // Use the filter_complex_script file
    cmd.addOption('-filter_complex_script', scriptPath);

    // Map the final video label
    const outOptions = [
      `-map`, `${finalVideoLabel}`,
      `-c:v`, `libx264`,
      `-pix_fmt`, `yuv420p`,
      `-preset`, config.ffmpegPreset,
      `-crf`, `23`,
      `-threads`, String(config.ffmpegThreads),
      `-movflags`, `+faststart`,
    ];

    if (audioPath) {
      outOptions.push(
        `-map`, `${audioInputIndex}:a`,
        `-c:a`, `aac`,
        `-b:a`, `192k`,
        `-shortest` // end when the shorter stream ends
      );
    }

    cmd.outputOptions(outOptions);
    cmd.output(outputPath);

    // Capture stderr
    cmd.on('stderr', (line) => {
      console.log('FFMPEG:', line);
      stderrLines.push(line);
      // Keep memory bounded during long encodes
      if (stderrLines.length > 5000) stderrLines = stderrLines.slice(-4000);
    });

    cmd.on('error', (err) => {
      const stderrSnippet = stderrLines.join('\n').slice(-2000);
      const enriched = new Error(`FFmpeg error: ${err.message}`);
      enriched.ffmpegStderr = stderrSnippet;
      enriched.killed = killed;
      reject(enriched);
    });

    cmd.on('end', () => {
      resolve(outputPath);
    });

    // Wire abort signal -> kill ffmpeg.
    //
    // cmd.kill() alone is NOT sufficient: fluent-ffmpeg only forwards the signal
    // when its internal `ffmpegProc` is set, and that is null while it is still
    // running its capability probe. An abort arriving in that window was a
    // silent no-op and the child kept running — so a "killed" hang could still
    // hold its resources. The pid captured on 'start' is killed directly too, so
    // the kill no longer depends on fluent-ffmpeg's internal state.
    let spawnedProc = null;
    cmd.on('start', () => {
      spawnedProc = cmd.ffmpegProc ?? null;
    });

    if (signal) {
      signal.addEventListener('abort', () => {
        killed = true;
        try {
          cmd.kill('SIGKILL');
        } catch {
          // already dead
        }
        const pid = spawnedProc?.pid ?? cmd.ffmpegProc?.pid;
        if (pid) {
          try {
            process.kill(pid, 'SIGKILL');
          } catch {
            // already reaped
          }
        }
      }, { once: true });
    }

    cmd.run();
    });
  } finally {
    releaseFfmpeg();
  }
}
/**
 * Uploads the finished file to a pre-signed URL via HTTP PUT.
 *
 * @param {string} filePath      - Local file path to upload
 * @param {string} uploadUrl     - Pre-signed PUT URL (e.g. Supabase Storage)
 * @param {AbortSignal} signal
 */
async function uploadOutput(filePath, uploadUrl, signal) {
  const stat = await fsp.stat(filePath);
  const rssMb = () => Math.round(process.memoryUsage().rss / 1048576);

  logger.info({ uploadUrl, size: stat.size, rssBeforeMb: rssMb() }, 'Uploading render output');

  // ── Streamed with http.request, NOT fetch ────────────────────────────────
  //
  // The original read the whole output with fsp.readFile and passed the Buffer
  // to fetch. A 1.38 GB file produced 8.36 GB of anon-rss and the kernel
  // OOM-killed the worker at the container limit (dmesg, CONSTRAINT_MEMCG,
  // task=node, anon-rss 8,362,628 kB). BullMQ then reported the surviving
  // stitch jobs as stalled, which is why three of five projects in the
  // 2026-08-07 run produced no video at all.
  //
  // Streaming into fetch does NOT fix it. Measured on a 1,335 MB file:
  //
  //   fsp.readFile + fetch(Buffer)          peak RSS 4,070 MB
  //   createReadStream + fetch(stream)      peak RSS 1,418 MB  (arrayBuffers 1,352 MB)
  //   createReadStream + http.request         peak RSS    90 MB  (arrayBuffers    32 MB)
  //
  // undici retains the whole body regardless of the body being a stream — with
  // Readable.toWeb, with a bare Readable, and with or without Content-Length.
  // Only the classic request path applies real backpressure, so that is what
  // this uses. Revisit only with a measurement, not with a version bump.
  const target = new URL(uploadUrl);
  const transport = target.protocol === 'http:' ? http : https;

  const response = await new Promise((resolve, reject) => {
    const req = transport.request(
      {
        protocol: target.protocol,
        hostname: target.hostname,
        port: target.port || (target.protocol === 'http:' ? 80 : 443),
        path: `${target.pathname}${target.search}`,
        method: 'PUT',
        headers: {
          'Content-Type': 'video/mp4',
          // Explicit: a stream body would otherwise be sent chunked, and the
          // pre-signed PUT requires a length.
          'Content-Length': String(stat.size),
        },
      },
      (res) => {
        let body = '';
        // Bounded — an error page is diagnostic, and this is the one place a
        // response body could itself become a memory problem.
        res.setEncoding('utf8');
        res.on('data', (chunk) => {
          if (body.length < 2048) body += chunk;
        });
        res.on('end', () => resolve({ status: res.statusCode || 0, body }));
      },
    );

    req.on('error', reject);

    const onAbort = () => {
      req.destroy(new Error('Upload aborted'));
    };
    if (signal) {
      if (signal.aborted) return onAbort();
      signal.addEventListener('abort', onAbort, { once: true });
      req.on('close', () => signal.removeEventListener('abort', onAbort));
    }

    // pipeline destroys both ends on failure, so a broken socket cannot leave
    // the read stream open holding a descriptor.
    pipelineAsync(createReadStream(filePath, { highWaterMark: 1 << 20 }), req).catch(reject);
  });

  if (response.status < 200 || response.status >= 300) {
    throw new Error(`Upload failed: HTTP ${response.status} - ${response.body.slice(0, 200)}`);
  }

  logger.info({ uploadUrl, size: stat.size, rssAfterMb: rssMb() }, 'Upload complete');
}

